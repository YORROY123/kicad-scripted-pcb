VIA_KEEP = 0.5  # 自動擺件離過孔中心至少這麼遠(過孔半徑 0.3 + 間隙)


def rects(pts) -> list:
    """直角多邊形 → 矩形(水平切片)。外接框會把 L 形 / 缺口裡的零件位置也擋掉。"""
    ys = sorted({y for _, y in pts})
    edges = [(pts[i], pts[(i + 1) % len(pts)]) for i in range(len(pts))]
    out = []
    for y0, y1 in zip(ys, ys[1:]):
        ym = (y0 + y1) / 2
        xs = sorted(a[0] for a, b in edges if a[0] == b[0] and min(a[1], b[1]) < ym < max(a[1], b[1]))
        out += [(xs[i], y0, xs[i + 1], y1) for i in range(0, len(xs), 2)]
    return out


def keepouts() -> list:
    """自動擺件的禁區:每個銅區(切成矩形)與每個過孔周圍。"""
    out = []
    for _, _, pts in POURS:
        out += rects(pts)
    for _, pts in VIA_FIELDS:
        out += [(x - VIA_KEEP, y - VIA_KEEP, x + VIA_KEEP, y + VIA_KEEP) for x, y in pts]
    return out
